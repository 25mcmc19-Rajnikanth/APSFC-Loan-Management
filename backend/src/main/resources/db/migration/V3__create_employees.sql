-- V3: employees table - internal staff profiles, 1:1 with users.

CREATE TABLE employees (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id       BIGINT       NOT NULL,
    employee_code VARCHAR(20)  NOT NULL,
    department    VARCHAR(60),
    designation   VARCHAR(60),
    joining_date  DATE,
    status        VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uk_employees_user      UNIQUE (user_id),
    CONSTRAINT uk_employees_code      UNIQUE (employee_code),
    CONSTRAINT chk_employees_status   CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT fk_employees_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT
);