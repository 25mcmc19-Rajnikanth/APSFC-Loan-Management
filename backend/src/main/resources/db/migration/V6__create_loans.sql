-- V6: loans table - created atomically at disbursement (1:1 with a disbursed
-- loan_application). Outstanding balance is maintained transactionally by the
-- repayment workflow; total_amount is the full contractual repayment.

CREATE TABLE loans (
    id                  BIGINT        GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    loan_number         VARCHAR(30)   NOT NULL,
    application_id      BIGINT        NOT NULL,
    customer_id         BIGINT        NOT NULL,
    product_id          BIGINT        NULL,
    principal_amount    DECIMAL(19,2) NOT NULL,
    interest_rate       DECIMAL(5,2)  NOT NULL,
    tenure_months       INTEGER       NOT NULL,
    monthly_emi         DECIMAL(19,2) NOT NULL,
    total_interest      DECIMAL(19,2) NOT NULL,
    total_amount        DECIMAL(19,2) NOT NULL,
    disbursed_amount    DECIMAL(19,2) NOT NULL,
    disbursement_date   DATE          NOT NULL,
    amount_paid         DECIMAL(19,2) NOT NULL DEFAULT 0.00,
    outstanding_balance DECIMAL(19,2) NOT NULL,
    status              VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE',
    disbursed_by        BIGINT        NULL,
    closed_at           TIMESTAMP     NULL,
    created_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uk_loans_number        UNIQUE (loan_number),
    CONSTRAINT uk_loans_application   UNIQUE (application_id),
    CONSTRAINT fk_loans_application
        FOREIGN KEY (application_id) REFERENCES loan_applications (id) ON DELETE RESTRICT,
    CONSTRAINT fk_loans_customer
        FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE RESTRICT,
    CONSTRAINT fk_loans_product
        FOREIGN KEY (product_id) REFERENCES loan_products (id) ON DELETE SET NULL,
    CONSTRAINT fk_loans_disbursed_by
        FOREIGN KEY (disbursed_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_loan_principal    CHECK (principal_amount > 0),
    CONSTRAINT chk_loan_disbursed    CHECK (disbursed_amount > 0),
    CONSTRAINT chk_loan_status       CHECK (status IN ('ACTIVE', 'CLOSED')),
    CONSTRAINT chk_loan_outstanding  CHECK (outstanding_balance >= 0)
);