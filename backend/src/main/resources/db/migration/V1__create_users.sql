-- V1: users table - login identity, role and account status.
-- Design note: a single role per user (CUSTOMER / LOAN_OFFICER / MANAGER / ADMIN)
-- is the correct domain model here, so no roles join-table is required.
-- Postgres notes: IDs use standard SQL identity columns; audit stamps are
-- maintained by Hibernate (@CreationTimestamp / @UpdateTimestamp) since
-- PostgreSQL has no ON UPDATE CURRENT_TIMESTAMP clause.

CREATE TABLE users (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    username      VARCHAR(50)  NOT NULL,
    email         VARCHAR(120) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(120) NOT NULL,
    phone         VARCHAR(20),
    role          VARCHAR(20)  NOT NULL,
    status        VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    last_login_at TIMESTAMP    NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email    UNIQUE (email),
    CONSTRAINT chk_users_role    CHECK (role IN ('CUSTOMER', 'LOAN_OFFICER', 'MANAGER', 'ADMIN')),
    CONSTRAINT chk_users_status  CHECK (status IN ('ACTIVE', 'INACTIVE', 'LOCKED'))
);