-- V8: repayments table - payment ledger. emi_allocation_id points at the first
-- EMI touched by this payment, but remains NULL-able because repayment can be
-- recorded before/allocation is validated (and early payments may target later
-- installments).

CREATE TABLE repayments (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    loan_id            BIGINT        NOT NULL,
    emi_allocation_id  BIGINT        NULL,
    amount             DECIMAL(19,2) NOT NULL,
    payment_mode       VARCHAR(20)   NOT NULL,
    transaction_ref    VARCHAR(60),
    payment_date       DATE          NOT NULL,
    created_by         BIGINT        NULL,
    remarks            VARCHAR(255),
    created_at         TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_repayments_loan
        FOREIGN KEY (loan_id) REFERENCES loans (id) ON DELETE RESTRICT,
    CONSTRAINT fk_repayments_allocation
        FOREIGN KEY (emi_allocation_id) REFERENCES emi_schedule (id) ON DELETE SET NULL,
    CONSTRAINT fk_repayments_created_by
        FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_repayment_amount CHECK (amount > 0),
    CONSTRAINT chk_repayment_mode CHECK (payment_mode IN ('CASH', 'UPI', 'NEFT', 'IMPS', 'RTGS', 'CHEQUE'))
);