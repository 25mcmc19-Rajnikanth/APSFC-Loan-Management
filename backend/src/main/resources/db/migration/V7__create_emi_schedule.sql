-- V7: emi_schedule table - one row per installment, generated on disbursement.

CREATE TABLE emi_schedule (
    id                  BIGINT        GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    loan_id             BIGINT        NOT NULL,
    emi_number          INTEGER       NOT NULL,
    due_date            DATE          NOT NULL,
    principal_component DECIMAL(19,2) NOT NULL,
    interest_component  DECIMAL(19,2) NOT NULL,
    total_amount        DECIMAL(19,2) NOT NULL,
    cumulative_paid     DECIMAL(19,2) NOT NULL DEFAULT 0.00,
    payment_status      VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    paid_date           DATE          NULL,
    created_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uk_emi_loan_number UNIQUE (loan_id, emi_number),
    CONSTRAINT fk_emi_loan
        FOREIGN KEY (loan_id) REFERENCES loans (id) ON DELETE RESTRICT,
    CONSTRAINT chk_emi_status CHECK (payment_status IN ('PENDING', 'PARTIALLY_PAID', 'PAID'))
);