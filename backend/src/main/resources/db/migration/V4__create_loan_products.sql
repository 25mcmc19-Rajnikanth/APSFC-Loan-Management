-- V4: loan_products table - configurable loan products. New products can be
-- added without touching core loan-processing logic.

CREATE TABLE loan_products (
    id                    BIGINT        GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name                  VARCHAR(120)  NOT NULL,
    code                  VARCHAR(30)   NOT NULL,
    description           VARCHAR(500),
    min_amount            DECIMAL(19,2) NOT NULL,
    max_amount            DECIMAL(19,2) NOT NULL,
    base_interest_rate    DECIMAL(5,2)  NOT NULL,
    min_tenure_months     INTEGER       NOT NULL,
    max_tenure_months     INTEGER       NOT NULL,
    eligibility_criteria  VARCHAR(500),
    status                VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE',
    created_at            TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uk_loan_products_code UNIQUE (code),
    CONSTRAINT chk_product_amounts  CHECK (min_amount > 0 AND max_amount >= min_amount),
    CONSTRAINT chk_product_rate     CHECK (base_interest_rate > 0),
    CONSTRAINT chk_product_tenure   CHECK (min_tenure_months > 0 AND max_tenure_months >= min_tenure_months),
    CONSTRAINT chk_product_status   CHECK (status IN ('ACTIVE', 'INACTIVE'))
);