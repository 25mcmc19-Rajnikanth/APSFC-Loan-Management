-- V5: loan_applications table + application_history audit trail.

CREATE TABLE loan_applications (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    application_number VARCHAR(30)   NOT NULL,
    customer_id        BIGINT        NOT NULL,
    product_id         BIGINT        NOT NULL,
    loan_amount        DECIMAL(19,2) NOT NULL,
    tenure_months      INTEGER       NOT NULL,
    interest_rate      DECIMAL(5,2)  NOT NULL,
    monthly_emi        DECIMAL(19,2) NOT NULL,
    purpose            VARCHAR(255),
    status             VARCHAR(30)   NOT NULL DEFAULT 'DRAFT',
    submitted_by       BIGINT        NULL,
    reviewed_by        BIGINT        NULL,
    approved_by        BIGINT        NULL,
    review_comment     VARCHAR(500),
    decision_comment   VARCHAR(500),
    submitted_at       TIMESTAMP     NULL,
    reviewed_at        TIMESTAMP     NULL,
    decided_at         TIMESTAMP     NULL,
    created_at         TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uk_application_number UNIQUE (application_number),
    CONSTRAINT fk_applications_customer
        FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE RESTRICT,
    CONSTRAINT fk_applications_product
        FOREIGN KEY (product_id) REFERENCES loan_products (id) ON DELETE RESTRICT,
    CONSTRAINT fk_applications_submitted_by
        FOREIGN KEY (submitted_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_applications_reviewed_by
        FOREIGN KEY (reviewed_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_applications_approved_by
        FOREIGN KEY (approved_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_application_amount CHECK (loan_amount > 0),
    CONSTRAINT chk_application_tenure CHECK (tenure_months > 0),
    CONSTRAINT chk_application_emi    CHECK (monthly_emi > 0),
    CONSTRAINT chk_application_status CHECK (status IN
        ('DRAFT', 'SUBMITTED', 'UNDER_REVIEW', 'APPROVED', 'REJECTED', 'CANCELLED', 'DISBURSED'))
);

CREATE TABLE application_history (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    application_id BIGINT       NOT NULL,
    from_status    VARCHAR(30),
    to_status      VARCHAR(30)  NOT NULL,
    action         VARCHAR(30)  NOT NULL,
    comment        VARCHAR(500),
    performed_by   BIGINT       NOT NULL,
    performed_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_history_application
        FOREIGN KEY (application_id) REFERENCES loan_applications (id) ON DELETE CASCADE,
    CONSTRAINT fk_history_performed_by
        FOREIGN KEY (performed_by) REFERENCES users (id) ON DELETE RESTRICT
);